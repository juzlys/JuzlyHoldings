# 1. Verify Uniqueness
$keys = $finalMasterMap.Keys
$values = $finalMasterMap.Values

$keyDups = $keys | Group-Object | Where-Object { $_.Count -gt 1 }
$valDups = $values | Group-Object | Where-Object { $_.Count -gt 1 }

if ($keyDups) {
    Write-Error "Duplicate keys found!"
    $keyDups | Format-Table
    exit 1
}

if ($valDups) {
    Write-Error "Duplicate photo IDs found!"
    $valDups | Format-Table
    exit 1
}

Write-Host "Uniqueness check passed: All $($keys.Count) filenames and $($values.Count) photo IDs are 100% UNIQUE!"

# 2. Download each image if missing or small
$success = 0
$failed = 0

foreach ($entry in $finalMasterMap.GetEnumerator()) {
    $filename = $entry.Key
    $photoId = $entry.Value
    $targetPath = "images/$filename"

    # Download if not present or < 10KB
    if (-not (Test-Path $targetPath) -or ((Get-Item $targetPath).Length -lt 10240)) {
        $url = "https://images.unsplash.com/$photoId`?q=80&w=1200&auto=format&fit=crop"
        $status = (curl.exe -L -s -o "$targetPath" -w "%{http_code}" --max-time 15 "$url")
        if ($status -eq "200" -and ((Get-Item $targetPath).Length -gt 10240)) {
            Write-Host "Downloaded: $filename ($((Get-Item $targetPath).Length) bytes)"
            $success++
        } else {
            Write-Warning "FAILED: $filename from $photoId ($status)"
            $failed++
        }
    } else {
        Write-Host "Existing: $filename ($((Get-Item $targetPath).Length) bytes)"
        $success++
    }
}

Write-Host "`nSummary: $success successful, $failed failed."
